#[cfg(test)]
mod tests {
    use super::*;
    use ipe_docs::env_vars::{ENV_VARS, EXCLUDED_NAMES};

    /// Resolve a workspace-root-relative path.
    fn workspace_path(rel: &str) -> PathBuf {
        let manifest = env!("CARGO_MANIFEST_DIR");
        PathBuf::from(manifest).join("../..").join(rel)
    }

    #[test]
    fn render_is_byte_idempotent() {
        let first = render_env_docs(ENV_VARS);
        let second = render_env_docs(ENV_VARS);
        assert_eq!(first, second, "two renders must be byte-identical");
    }

    #[test]
    fn render_contains_sentinel() {
        let out = render_env_docs(ENV_VARS);
        assert!(
            out.contains("Generated by gen-env-docs"),
            "output must carry the generated-file sentinel"
        );
    }

    #[test]
    fn render_contains_known_vars() {
        let out = render_env_docs(ENV_VARS);
        assert!(
            out.contains("`IPE_LOG_LEVEL`"),
            "must contain IPE_LOG_LEVEL"
        );
        assert!(
            out.contains("`IPE_ADMIN_TOKEN`"),
            "must contain IPE_ADMIN_TOKEN"
        );
        assert!(
            out.contains("`IPE_HTTP_DENY_PRIVATE`"),
            "must contain IPE_HTTP_DENY_PRIVATE"
        );
    }

    #[test]
    fn render_contains_class_badges() {
        let out = render_env_docs(ENV_VARS);
        assert!(
            out.contains("`Secret`"),
            "must have at least one Secret badge"
        );
        assert!(
            out.contains("`SecurityTunable`"),
            "must have at least one SecurityTunable badge"
        );
        assert!(
            out.contains("`Tunable`"),
            "must have at least one Tunable badge"
        );
    }

    /// Drift gate: every `IPE_*` string literal read in the codebase must
    /// appear in `ENV_VARS` or `EXCLUDED_NAMES`.
    ///
    /// The gate scans `src/` for patterns matching `"IPE_[A-Z_]+"` and
    /// verifies coverage. A variable that is read but undocumented fails the
    /// build, making the reference unable to drift.
    #[test]
    fn all_runtime_env_vars_are_documented() {
        // Collect literals from the source tree.
        let src_root = workspace_path("src");
        let tools_root = workspace_path("tools");

        let found = scan_ipe_literals(&src_root)
            .into_iter()
            .chain(scan_ipe_literals(&tools_root));

        let registered: std::collections::HashSet<&str> = ENV_VARS.iter().map(|v| v.name).collect();
        let excluded: std::collections::HashSet<&str> = EXCLUDED_NAMES.iter().copied().collect();

        let mut undocumented: Vec<String> = Vec::new();
        for name in found {
            if !registered.contains(name.as_str()) && !excluded.contains(name.as_str()) {
                undocumented.push(name);
            }
        }
        undocumented.sort();
        undocumented.dedup();

        assert!(
            undocumented.is_empty(),
            "These `IPE_*` variables are read in the codebase but not documented in \
             ENV_VARS or EXCLUDED_NAMES:\n{}\n\n\
             Add each to `src/ipe-docs/src/env_vars.rs` (either `ENV_VARS` for \
             operator-facing vars, or `EXCLUDED_NAMES` for test/internal-only ones).",
            undocumented.join("\n")
        );
    }

    /// Committed file must match what the generator produces today.
    ///
    /// Run `cargo run -p ipe_docs --bin gen-env-docs` to regenerate.
    #[test]
    fn committed_env_md_matches_generator() {
        let path = workspace_path("docs/reference/env.md");
        let committed = std::fs::read_to_string(&path).expect(
            "cannot read docs/reference/env.md; \
             run `cargo run -p ipe_docs --bin gen-env-docs` to generate it",
        );
        let generated = render_env_docs(ENV_VARS);
        assert_eq!(
            committed, generated,
            "docs/reference/env.md is out of date.\n\
             Run `cargo run -p ipe_docs --bin gen-env-docs` to regenerate it."
        );
    }

    // ── Helpers ──────────────────────────────────────────────────────────────

    /// Walk a directory tree and collect all `IPE_[A-Z_]+` string literals
    /// found in `.rs` files (excluding test files `tests/` and `*_test.rs`).
    fn scan_ipe_literals(root: &std::path::Path) -> std::collections::HashSet<String> {
        let mut found = std::collections::HashSet::new();
        if let Ok(entries) = walkdir(root) {
            for path in entries {
                // Skip non-Rust files.
                if path.extension().and_then(|e| e.to_str()) != Some("rs") {
                    continue;
                }
                // Skip pure test files (test support, golden harness, etc.).
                // We still scan test files that are part of a crate (the drift
                // gate is about what the crate READS, including test helpers).
                let Ok(src) = std::fs::read_to_string(&path) else {
                    continue;
                };
                for cap in extract_ipe_literals(&src) {
                    found.insert(cap);
                }
            }
        }
        found
    }

    /// Extract all `"IPE_[A-Z_]+"` string literals from a Rust source string.
    fn extract_ipe_literals(src: &str) -> Vec<String> {
        let mut out = Vec::new();
        let mut rest = src;
        while let Some(pos) = rest.find("\"IPE_") {
            rest = &rest[pos + 1..]; // skip the opening quote
            let end = rest.find('"').unwrap_or(rest.len());
            let candidate = &rest[..end];
            if is_valid_ipe_name(candidate) {
                out.push(candidate.to_owned());
            }
            rest = &rest[end..];
        }
        out
    }

    /// Return true when `s` matches `IPE_[A-Z][A-Z0-9_]*` (non-empty suffix) and
    /// is not a diagnostic-code token.
    ///
    /// A diagnostic code has the shape `IPE_<letter><digits>` (e.g. `IPE_N0028`) —
    /// a single uppercase letter followed only by digits. Those are never
    /// environment-variable names (real ones carry more structure, e.g.
    /// `IPE_E2E`, `IPE_RUNTIME_DIR`), so they are excluded to keep the two
    /// `IPE_`-prefixed vocabularies from colliding in this scan.
    fn is_valid_ipe_name(s: &str) -> bool {
        let Some(suffix) = s.strip_prefix("IPE_") else {
            return false;
        };
        if suffix.is_empty() {
            return false;
        }
        if !suffix
            .chars()
            .all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_')
        {
            return false;
        }
        let first_is_letter = suffix
            .chars()
            .next()
            .is_some_and(|c| c.is_ascii_uppercase());
        let rest_all_digits =
            suffix.len() > 1 && suffix.chars().skip(1).all(|c| c.is_ascii_digit());
        !(first_is_letter && rest_all_digits)
    }

    /// Collect all regular-file paths under `root` recursively.
    fn walkdir(root: &std::path::Path) -> std::io::Result<Vec<std::path::PathBuf>> {
        let mut result = Vec::new();
        if !root.exists() {
            return Ok(result);
        }
        let mut stack = vec![root.to_owned()];
        while let Some(dir) = stack.pop() {
            for entry in std::fs::read_dir(&dir)?.flatten() {
                let path = entry.path();
                if path.is_dir() {
                    // Skip hidden dirs and target dirs.
                    let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
                    if !name.starts_with('.') && name != "target" {
                        stack.push(path);
                    }
                } else {
                    result.push(path);
                }
            }
        }
        Ok(result)
    }
}
