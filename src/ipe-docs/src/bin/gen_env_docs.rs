//! Generator for `docs/reference/env.md`.
//!
//! Reads the `ENV_VARS` registry in `ipe_docs::env_vars` and renders a
//! reference page grouped by subsystem, with a badge per variable indicating
//! its operational class (Tunable / Secret / `SecurityTunable`).
//!
//! The output is deterministic: subsystems and variables appear in registry
//! order, so the same registry always produces byte-identical output.
//!
//! # Usage
//!
//! ```text
//! cargo run -p ipe_docs --bin gen-env-docs -- --repo-root <path>
//! ```
//!
//! By default `--repo-root` is the workspace root located by walking upward
//! from `CARGO_MANIFEST_DIR`.

#![forbid(unsafe_code)]

use std::fmt::Write as FmtWrite;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use ipe_docs::env_vars::{Class, ENV_VARS, EnvVar, Subsystem};

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("gen-env-docs: {e}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> Result<(), String> {
    let repo_root = find_repo_root()?;
    let content = render_env_docs(ENV_VARS);
    write_file(&repo_root.join("docs/reference/env.md"), &content)?;
    Ok(())
}

// ── Renderer ─────────────────────────────────────────────────────────────────

/// Render `docs/reference/env.md` from the registry slice.
///
/// Variables are emitted in registry order (grouped by subsystem as laid out
/// in `env_vars.rs`). The output is byte-identical for the same input.
#[must_use]
pub fn render_env_docs(vars: &[EnvVar]) -> String {
    let mut out = String::new();

    out.push_str("<!-- Generated by gen-env-docs. Do not edit by hand. -->\n\n");
    out.push_str("# Environment variables\n\n");
    out.push_str(
        "Every `IPE_*` variable the runtime, CLI, and compiler read. \
         The table is grouped by subsystem; each row shows the name, default, \
         one-line effect, and class badge.\n\n",
    );
    out.push_str("**Class badges**\n\n");
    out.push_str("- `Tunable` — safe to adjust; the default is always the conservative choice.\n");
    out.push_str(
        "- `Secret` — a credential (token, key, password). \
         Provide via your secret manager; never commit or log the value.\n",
    );
    out.push_str(
        "- `SecurityTunable` — a security-boundary switch. \
         Loosening widens the trust boundary; understand the trade-off before \
         changing from the default.\n\n",
    );

    // Table of contents.
    out.push_str("## Subsystems\n\n");
    let subsystems = collect_subsystems(vars);
    for sub in &subsystems {
        let anchor = subsystem_anchor(sub.display());
        let _ = writeln!(out, "- [{name}](#{anchor})", name = sub.display());
    }
    out.push('\n');

    // Per-subsystem sections.
    for sub in &subsystems {
        let sub_vars: Vec<&EnvVar> = vars.iter().filter(|v| v.subsystem == *sub).collect();
        emit_subsystem_section(&mut out, *sub, &sub_vars);
    }

    out
}

/// Emit one subsystem section: a heading followed by a Markdown table.
fn emit_subsystem_section(out: &mut String, sub: Subsystem, vars: &[&EnvVar]) {
    let _ = writeln!(out, "## {}\n", sub.display());
    out.push_str("| Variable | Default | Effect | Class |\n");
    out.push_str("|----------|---------|--------|-------|\n");
    for v in vars {
        let class_badge = class_badge(v.class);
        // Escape pipe characters in cell text so Markdown tables stay valid.
        let purpose = v.purpose.replace('|', "\\|");
        let default = v.default.replace('|', "\\|");
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} |",
            v.name, default, purpose, class_badge
        );
    }
    out.push('\n');
}

/// Render the class as a Markdown inline-code badge.
const fn class_badge(class: Class) -> &'static str {
    match class {
        Class::Tunable => "`Tunable`",
        Class::Secret => "`Secret`",
        Class::SecurityTunable => "`SecurityTunable`",
    }
}

/// Collect the unique subsystems in registry order (first occurrence wins).
fn collect_subsystems(vars: &[EnvVar]) -> Vec<Subsystem> {
    let mut seen = std::collections::HashSet::new();
    let mut out = Vec::new();
    for v in vars {
        if seen.insert(v.subsystem) {
            out.push(v.subsystem);
        }
    }
    out
}

/// Convert a subsystem display name to a GitHub Markdown anchor slug.
fn subsystem_anchor(name: &str) -> String {
    name.chars()
        .filter_map(|c| {
            if c.is_alphanumeric() {
                Some(c.to_ascii_lowercase())
            } else if c == ' ' || c == '-' {
                Some('-')
            } else {
                None
            }
        })
        .collect()
}

// ── Helpers ───────────────────────────────────────────────────────────────────

fn find_repo_root() -> Result<PathBuf, String> {
    let mut args = ipe_docs::argv::host_args()
        .map_err(|e| e.to_string())?
        .into_iter();
    while let Some(arg) = args.next() {
        if arg == "--repo-root" {
            let path = args
                .next()
                .ok_or_else(|| "--repo-root requires a path argument".to_owned())?;
            return Ok(PathBuf::from(path));
        }
    }
    let manifest_dir = env!("CARGO_MANIFEST_DIR");
    find_workspace_root(Path::new(manifest_dir))
}

fn find_workspace_root(start: &Path) -> Result<PathBuf, String> {
    let mut current = start;
    loop {
        let candidate = current.join("Cargo.toml");
        if candidate.exists() {
            let content = std::fs::read_to_string(&candidate)
                .map_err(|e| format!("cannot read {}: {e}", candidate.display()))?;
            if content.contains("[workspace]") {
                return Ok(current.to_owned());
            }
        }
        match current.parent() {
            Some(parent) => current = parent,
            None => return Err("workspace root not found — pass --repo-root".to_owned()),
        }
    }
}

fn write_file(path: &Path, content: &str) -> Result<(), String> {
    std::fs::write(path, content).map_err(|e| format!("cannot write {}: {e}", path.display()))
}

