//! Generator for `docs/reference/capabilities.md`.
//!
//! Reads `Capability::ALL` from `ipe_kernels` and renders a reference page
//! grouped by boundary class, with a table row per capability axis showing
//! its wire name and what granting it permits.
//!
//! The output is deterministic: boundary classes and capability rows appear in
//! `Capability::ALL` order, so the same SSOT always produces byte-identical
//! output. Adding a new `Capability` variant without regenerating the committed
//! file causes the drift gate (`capabilities-docs-drift` in CI) to fail.
//!
//! # Usage
//!
//! ```text
//! cargo run -p ipe_docs --bin gen-capabilities-docs -- --repo-root <path>
//! ```
//!
//! By default `--repo-root` is the workspace root located by walking upward
//! from `CARGO_MANIFEST_DIR`.

#![forbid(unsafe_code)]

use std::fmt::Write as FmtWrite;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use ipe_docs::markdown_text;
use ipe_kernels::Capability;

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("gen-capabilities-docs: {e}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> Result<(), String> {
    let repo_root = find_repo_root()?;
    let content = render_capabilities_docs(Capability::ALL);
    write_file(&repo_root.join("docs/reference/capabilities.md"), &content)?;
    Ok(())
}

// ── Renderer ──────────────────────────────────────────────────────────────────

/// Render `docs/reference/capabilities.md` from the closed capability slice.
///
/// Rows appear in `Capability::ALL` order, grouped by boundary class.
/// The output is byte-identical for the same input.
#[must_use]
pub fn render_capabilities_docs(caps: &[Capability]) -> String {
    let mut out = String::new();

    out.push_str("<!-- Generated by gen-capabilities-docs. Do not edit by hand. -->\n\n");
    out.push_str("# Capabilities\n\n");
    out.push_str(
        "Ipê runs programs under a deny-by-default capability model. \
         Every operation that touches an OS resource, crosses a trust boundary, \
         or exercises non-determinism maps to exactly one capability axis. \
         A program's capability set is the union over its transitively-reachable \
         kernels; any axis not in that set is denied at the sandbox layer. \
         The axes are declared once in the compiler's closed `Capability` enum \
         and cannot be extended without a source change.\n\n",
    );

    // Collect the unique boundary classes in ALL order (first occurrence wins).
    let classes = collect_classes(caps);

    // Table of contents.
    out.push_str("## Boundary classes\n\n");
    for class in &classes {
        let anchor = class_anchor(class);
        let _ = writeln!(out, "- [{class}](#{anchor})");
    }
    out.push('\n');

    // Per-class sections.
    for class in &classes {
        let class_caps: Vec<Capability> = caps
            .iter()
            .copied()
            .filter(|c| c.boundary_class() == *class)
            .collect();
        emit_class_section(&mut out, class, &class_caps);
    }

    out
}

/// Emit one boundary-class section: a heading followed by a Markdown table.
fn emit_class_section(out: &mut String, class: &str, caps: &[Capability]) {
    let _ = writeln!(out, "## {class}\n");
    out.push_str("| Wire name | Grants |\n");
    out.push_str("|-----------|--------|\n");
    for cap in caps {
        let wire = markdown_text::table_cell(cap.as_str());
        let grants = markdown_text::table_cell(cap.grants());
        let _ = writeln!(out, "| `{wire}` | {grants} |");
    }
    out.push('\n');
}

/// Collect unique boundary-class strings in `ALL` order.
fn collect_classes(caps: &[Capability]) -> Vec<&'static str> {
    let mut seen = std::collections::HashSet::new();
    let mut out = Vec::new();
    for cap in caps {
        let class = cap.boundary_class();
        if seen.insert(class) {
            out.push(class);
        }
    }
    out
}

/// Convert a boundary-class name to a GitHub Markdown anchor slug.
fn class_anchor(name: &str) -> String {
    name.chars()
        .filter_map(|c| {
            if c.is_alphanumeric() {
                Some(c.to_ascii_lowercase())
            } else if c == ' ' || c == '-' {
                Some('-')
            } else {
                None
            }
        })
        .collect()
}

// ── Helpers ───────────────────────────────────────────────────────────────────

fn find_repo_root() -> Result<PathBuf, String> {
    let mut args = ipe_docs::argv::host_args()
        .map_err(|e| e.to_string())?
        .into_iter();
    while let Some(arg) = args.next() {
        if arg == "--repo-root" {
            let path = args
                .next()
                .ok_or_else(|| "--repo-root requires a path argument".to_owned())?;
            return Ok(PathBuf::from(path));
        }
    }
    let manifest_dir = env!("CARGO_MANIFEST_DIR");
    find_workspace_root(Path::new(manifest_dir))
}

fn find_workspace_root(start: &Path) -> Result<PathBuf, String> {
    let mut current = start;
    loop {
        let candidate = current.join("Cargo.toml");
        if candidate.exists() {
            let content = std::fs::read_to_string(&candidate)
                .map_err(|e| format!("cannot read {}: {e}", candidate.display()))?;
            if content.contains("[workspace]") {
                return Ok(current.to_owned());
            }
        }
        match current.parent() {
            Some(parent) => current = parent,
            None => return Err("workspace root not found — pass --repo-root".to_owned()),
        }
    }
}

fn write_file(path: &Path, content: &str) -> Result<(), String> {
    std::fs::write(path, content).map_err(|e| format!("cannot write {}: {e}", path.display()))
}

// ── Tests ─────────────────────────────────────────────────────────────────────

#[cfg(test)]
mod tests {
    use super::*;
    use ipe_kernels::Capability;

    /// Resolve a workspace-root-relative path.
    fn workspace_path(rel: &str) -> PathBuf {
        let manifest = env!("CARGO_MANIFEST_DIR");
        PathBuf::from(manifest).join("../..").join(rel)
    }

    #[test]
    fn render_is_byte_idempotent() {
        let first = render_capabilities_docs(Capability::ALL);
        let second = render_capabilities_docs(Capability::ALL);
        assert_eq!(first, second, "two renders must be byte-identical");
    }

    #[test]
    fn render_contains_sentinel() {
        let out = render_capabilities_docs(Capability::ALL);
        assert!(
            out.contains("Generated by gen-capabilities-docs"),
            "output must carry the generated-file sentinel"
        );
    }

    #[test]
    fn render_contains_every_wire_name() {
        let out = render_capabilities_docs(Capability::ALL);
        for cap in Capability::ALL {
            let wire = cap.as_str();
            assert!(
                out.contains(wire),
                "capabilities.md must contain wire name {wire:?}"
            );
        }
    }

    #[test]
    fn render_contains_all_boundary_classes() {
        let out = render_capabilities_docs(Capability::ALL);
        for class in ["OS resource", "Non-determinism", "Native crossing"] {
            assert!(
                out.contains(class),
                "capabilities.md must contain boundary class {class:?}"
            );
        }
    }

    /// Drift gate: the committed `docs/reference/capabilities.md` must
    /// byte-match the output of `render_capabilities_docs(Capability::ALL)`.
    ///
    /// A `Capability` variant added or modified without regenerating the
    /// committed file fails here, surfacing the gap in CI before it ships.
    #[test]
    fn committed_file_matches_generated_output() {
        let path = workspace_path("docs/reference/capabilities.md");
        let committed = std::fs::read_to_string(&path).expect(
            "cannot read docs/reference/capabilities.md; \
             run `cargo run -p ipe_docs --bin gen-capabilities-docs` to generate it",
        );
        let generated = render_capabilities_docs(Capability::ALL);
        assert_eq!(
            committed, generated,
            "docs/reference/capabilities.md is out of date — run \
             `cargo run -p ipe_docs --bin gen-capabilities-docs` and commit the result"
        );
    }
}
